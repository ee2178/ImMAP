"""Random Brownian-bridge paths for the I2SB talk's bridge figure -> bridge_paths.tex.

Figure units: horizontal X = 10 (1 - t), so the side information (t = 1) is at X = 0 and the
target (t = 0) at X = 10. Vertical: the straight line from y1 = 0.25 to y0 = -0.25 (the bridge
mean), plus sqrt(V) * a standard Brownian bridge, whose standard deviation sqrt(V t (1 - t)) is
the dashed envelope drawn in the talk. Path 0 is the highlighted one.

    python bridge_paths.py            # rewrites bridge_paths.tex next to this file
"""
import os

import numpy as np

SQRT_V = 2.8          # envelope half-width at t = 0.5 is SQRT_V / 2 = 1.4 (keep in sync with the .tex)
Y1, Y0 = 0.25, -0.25  # bridge endpoints: side information, target
N_PATHS, N_STEPS, SEED = 11, 160, 3
MAX_DEV = 2.0         # cosmetic: draw only paths whose excursion fits the slide


def main():
    rng = np.random.default_rng(SEED)
    tau = np.linspace(0.0, 1.0, N_STEPS + 1)                      # tau = 1 - t
    lines = ["% generated by bridge_paths.py -- do not edit by hand"]
    mean = Y1 + (Y0 - Y1) * tau
    kept = []
    while len(kept) < N_PATHS:      # keep paths that stay on the slide (|deviation| <= MAX_DEV)
        w = np.concatenate([[0.0], np.cumsum(rng.standard_normal(N_STEPS))]) / np.sqrt(N_STEPS)
        b = w - tau * w[-1]                                         # standard Brownian bridge
        if np.abs(SQRT_V * b).max() <= MAX_DEV:
            kept.append(b)
    for k, b in enumerate(kept):
        y = mean + SQRT_V * b
        pts = " ".join(f"({10 * a:.2f},{v:.3f})" for a, v in zip(tau, y))
        style = "bpathhi" if k == 0 else "bpath"
        lines.append(f"\\draw[{style}] plot coordinates {{{pts}}};")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "bridge_paths.tex")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
