#!/usr/bin/env python3
"""
The manuscript comparison figure: one picked slice per row, one method per column.

    python figures/make_figure.py figures/configs/main_knee_R8.py
    python figures/make_figure.py figures/configs/main_knee_R8.py --no-compile

Every panel is the same object: the slice with a green box, the metrics in its
top-right corner, and DIRECTLY BENEATH it the magnified box (left) and its
absolute residual against the ground truth (right, colour-mapped). Every
column of a row shares one FOV crop, one display window and one zoom box, so
the panels are comparable pixel for pixel. The ground-truth column carries the
legend: the metric names in its corner and the inset labels under it (its own
residual is black, so the text sits on empty space).

Reads what figures/viewer.py (or webviewer.py) picked for this config:

    rows/<VARIANT>.json    which volume and slice each row shows
    zooms/<VARIANT>.json   where each row's zoom box sits (else automatic)
    cols/<VARIANT>.json    which runs are the columns (the web viewer's Models
                           menu), else the config's COLUMNS

and the dumps scripts/dump_eval.py wrote. The crop, window, zoom and residual
come from figures/common.py -- `slice_view` and `zoom_pair`, the same functions
the viewer draws its zoom-mode strips with -- so the figure is what you placed.

Writes figures/out/<NAME>/: <NAME>.tex (standalone, tikz), imgs/ (pixel-exact
PNGs; insets nearest-neighbour upsampled by ZOOM_UP so they stay crisp in the
PDF), metrics.csv, and -- when pdflatex is found -- <NAME>.pdf, plus <NAME>.png
when pdftoppm is.

Metrics (FIG_METRICS, default psnr and ssim) are the per-slice values the dump
stored, i.e. what evaluation/metrics.py computed: organ-masked iff the run was
trained with the mask. NRMSE, if asked for, is recomputed here as
||gt - x|| / ||gt|| over the same mask, so dumps made before the 2026-10-20
NRMSE change still print the current definition. A column with no stored
metrics (the zero-filled adjoint) gets live PSNR and NRMSE, and no SSIM.

The layout follows the reco8pc_compare figure (make_figure.py there, part A).
"""

from __future__ import annotations

import argparse
import csv
import os
import re
import shutil
import subprocess
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from figures import common as fc                                    # noqa: E402
from figures.common import (auto_zoom, col_spec, disagreement, row_tag,  # noqa: E402
                            to8)

FMT = {"psnr": "{:.2f}", "ssim": "{:.3f}", "nrmse": "{:.3f}"}
NAMES = {"psnr": "PSNR", "ssim": "SSIM", "nrmse": "NRMSE"}


def safe(text):
    """A file-name-safe version of a label (LaTeX reads these paths)."""
    return re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-")


def short_id(volume):
    """`file_brain_AXT2_200_2000019` -> `2000019`; `file1000031` -> `1000031`."""
    m = re.search(r"(\d+)$", volume)
    return m.group(1) if m else fc.pretty(volume)


def live_psnr(ref, x, mask, data_range=1.0):
    """training.metrics.psnr's definition (masked mean). `data_range` is the dump's attr when it
    has one (NYUMets: the run's data_range, 2.0), else 1 -- what the stored values used."""
    se = (ref - x) ** 2
    mse = se[mask].mean() if mask is not None and mask.any() else se.mean()
    return float(10 * np.log10(data_range ** 2 / max(mse, 1e-30)))


def save_gray(path, a, vmax):
    Image.fromarray(to8(a, vmax), "L").save(path)


def save_inset(path, rgb):
    h, w = rgb.shape[:2]
    Image.fromarray(rgb, "RGB").resize((w * fc.ZOOM_UP, h * fc.ZOOM_UP),
                                       Image.NEAREST).save(path)


# --- tex -------------------------------------------------------------------
def tex_head():
    m = re.match(r"\s*([0-9.]+)\s*([a-z]+)\s*$", str(fc.IMG_WIDTH))
    if not m:
        raise SystemExit(f"IMG_WIDTH={fc.IMG_WIDTH!r}: give a length such as '3cm'")
    w, unit = float(m.group(1)), m.group(2)
    return rf"""% GENERATED by figures/make_figure.py -- edit that script or the config, not this file.
\documentclass[border=2pt]{{standalone}}
\usepackage{{tikz}}
\usepackage{{graphicx}}
\usepackage{{makecell}}
\usetikzlibrary{{calc}}

\def\imgw{{{w:g}{unit}}}      % displayed width of one panel
\def\insetw{{{0.495 * w:.4g}{unit}}}  % each inset: half a panel, less the border
\definecolor{{zoneA}}{{RGB}}{{0,220,0}}

% Each panel: the slice with a green box, metrics top-right (the ground-truth
% column names them); beneath it the magnified box (left) and its absolute
% residual against the ground truth (right).
\begin{{document}}
"""


def panel_tex(stem, metrics, zoom, W, legend=False):
    """Image + pixel-exact box, over the zoom and residual insets."""
    def xy(c, r):                      # tikz y runs up from the bottom edge
        return f"({c / W:.6f},{(W - r) / W:.6f})"

    c0, r0 = zoom
    box = (f"      \\draw[zoneA, line width=0.7pt] "
           f"{xy(c0, r0 + fc.ZOOM_H)} rectangle {xy(c0 + fc.ZOOM_W, r0)};")
    m = ("" if not metrics else
         "    \\node[anchor=north east, text=yellow, font=\\ttfamily\\scriptsize,"
         "\n         inner sep=1.5pt] at (img.north east) {\\makecell[r]{" + metrics + "}};")

    def tag(node, text, anchor):
        return ("" if not legend else
                f"\n    \\node[anchor={anchor}, text=yellow, font=\\ttfamily\\tiny,"
                f" inner sep=1.5pt, fill=black, fill opacity=0.5, text opacity=1]"
                f" at ({node}.{anchor}) {{{text}}};")

    gain = rf"$|\Delta|\times${fc.RESID_GAIN:g}"
    return f"""\\begin{{tikzpicture}}[inner sep=0pt, outer sep=0pt,
                    baseline={{(current bounding box.center)}}]
    \\node[anchor=south west] (img) {{\\includegraphics[width=\\imgw]{{imgs/{stem}.png}}}};
{m}
    \\begin{{scope}}[x={{(img.south east)-(img.south west)}},
                  y={{(img.north west)-(img.south west)}}, shift={{(img.south west)}}]
{box}
    \\end{{scope}}
    \\node[anchor=north west, draw=zoneA, line width=0.6pt, inner sep=0pt] (zm)
         at ($(img.south west)+(0pt,-1pt)$)
         {{\\includegraphics[width=\\insetw]{{imgs/{stem}_zoom.png}}}};
    \\node[anchor=north east, draw=zoneA, line width=0.6pt, inner sep=0pt] (rs)
         at ($(img.south east)+(0pt,-1pt)$)
         {{\\includegraphics[width=\\insetw]{{imgs/{stem}_resid.png}}}};\
{tag('zm', 'zoom', 'south west')}\
{tag('rs', gain, 'south east')}
\\end{{tikzpicture}}"""


def label_cell(text):
    """Rotated row label, centred on the row."""
    return (r"\begin{tikzpicture}[baseline={(current bounding box.center)}]"
            rf"\node[rotate=90]{{\small {text}}};\end{{tikzpicture}}")


def write_tex(path, headers, panels, labels):
    spec = "@{}c" + "@{\\hspace{1pt}}c" * len(headers) + "@{}"
    out = [tex_head(), r"\begin{tabular}{" + spec + "}"]
    if fc.FIG_TITLE:
        out.append(rf"& \multicolumn{{{len(headers)}}}{{c}}{{{fc.FIG_TITLE}}} \\[2pt]")
    out.append(" & ".join([""] + [rf"\small {h}" for h in headers]) + r" \\[1pt]")
    for cells, lab in zip(panels, labels):
        out.append(" &\n".join([label_cell(lab)] + cells) + r" \\[2pt]")
    out += [r"\end{tabular}", r"\end{document}"]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def find_tool(name):
    """`name` on PATH, else in a per-user MiKTeX install (Windows)."""
    hit = shutil.which(name)
    if hit:
        return hit
    local = os.environ.get("LOCALAPPDATA")
    if local:
        cand = os.path.join(local, "Programs", "MiKTeX", "miktex", "bin", "x64",
                            name + ".exe")
        if os.path.exists(cand):
            return cand
    return None


# --- driver ----------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config", help="config file (see figures/configs/)")
    ap.add_argument("--name", help="output name (rows/zooms still come from the config)")
    ap.add_argument("--dump-root", help="override DUMP_ROOT")
    ap.add_argument("--no-compile", action="store_true",
                    help="write the PNGs and the .tex, but do not run pdflatex")
    a = ap.parse_args()

    fc.apply_config(a.config)
    if a.name:
        fc.NAME = a.name
    if a.dump_root:
        fc.DUMP_ROOT = a.dump_root
    unknown = [m for m in fc.FIG_METRICS if m not in FMT]
    if unknown:
        raise SystemExit(f"FIG_METRICS: unknown {unknown}; choose from {sorted(FMT)}")

    rows = fc.active_rows()
    if not rows:
        raise SystemExit(f"no rows for '{fc.variant()}': pick them with "
                         f"figures/viewer.py (or webviewer.py) {a.config}, or set ROWS")
    zooms = fc.load_zooms()
    out = fc.outdir()
    imgs = os.path.join(out, "imgs")
    os.makedirs(imgs, exist_ok=True)
    for w in fc.check_comparable(rows[0]["volume"]):
        print(f"[warning] {w}")

    headers = [lab for lab, _ in fc.COLUMNS]
    is_ref = {lab: col_spec(spec)[1] == "reference" for lab, spec in fc.COLUMNS}
    legend_col = next((lab for lab in headers if is_ref[lab]), headers[-1])
    panels, labels, table = [], [], []

    src = "rows/" + fc.variant() + ".json" if os.path.exists(fc.rows_file()) else "config ROWS"
    print(f"{fc.variant()}: {len(rows)} row(s) from {src}, {len(zooms)} saved zoom(s)")
    print("columns: " + ", ".join(lab for lab, _ in fc.COLUMNS)
          + (f"   [from cols/{fc.variant()}.json -- the viewer's model menu]"
             if os.path.exists(fc.cols_file()) else "   [from the config]"))
    for ri, row in enumerate(rows):
        vol, sl = row["volume"], int(row["slice"])
        pos = fc.pos_of(vol, sl)
        if pos is None:
            raise SystemExit(f"row {ri}: slice {sl} of {vol} is not in the dump -- "
                             f"re-dump that range or re-pick the row")
        v = fc.slice_view(vol, pos, crop=fc.CROP_FOV)
        W = v["W"]
        tag = row_tag(row)
        zoom = tuple(row.get("zoom") or zooms.get(tag)
                     or auto_zoom(v["ref"], disagreement(v["ref"], v["methods"]), W))
        how = "row" if row.get("zoom") else "picked" if tag in zooms else "auto"
        masked = any(v["masked"].values())
        mask = v["organ"] if masked else None
        first = next(spec for _, spec in fc.COLUMNS if col_spec(spec)[0] is not None)
        data_range = float(fc.load(first, vol).attrs.get("data_range", 1.0))

        cells = []
        for lab in headers:
            stem = f"r{ri}-{short_id(vol)}-s{sl}-{safe(lab)}"
            save_gray(os.path.join(imgs, stem + ".png"), v["cols"][lab], v["vmax"])
            zl, zr = fc.zoom_pair(v, lab, zoom)
            save_inset(os.path.join(imgs, stem + "_zoom.png"), zl)
            save_inset(os.path.join(imgs, stem + "_resid.png"), zr)

            vals = {}
            if is_ref[lab]:
                text = r"\\".join(NAMES[m] for m in fc.FIG_METRICS)
            elif lab not in v["methods"] and not fc.FIG_INPUT_METRICS:
                text = ""                       # an input column: no metrics printed
            else:
                x, stored = v["cols"][lab], v["stored"].get(lab, {})
                for m in fc.FIG_METRICS:
                    if m == "nrmse":
                        vals[m] = fc.nrmse(v["ref"], x, mask)
                    elif m in stored:
                        vals[m] = float(stored[m])
                    elif m == "psnr":
                        vals[m] = live_psnr(v["ref"], x, mask, data_range)
                text = r"\\".join(FMT[m].format(vals[m]) if m in vals else "--"
                                  for m in fc.FIG_METRICS)
                table.append(dict(row=ri, volume=vol, slice=sl, column=lab,
                                  **{m: vals.get(m, "") for m in fc.FIG_METRICS}))
            cells.append(panel_tex(stem, text, zoom, W, legend=(lab == legend_col)))
        panels.append(cells)
        labels.append(rf"{short_id(vol)}, slice {sl}")
        print(f"  row {ri}: {fc.pretty(vol)} slice {sl}  zoom={zoom} [{how}]  "
              f"crop {W}px  vmax={v['vmax']:.3g}")

    with open(os.path.join(out, "metrics.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["row", "volume", "slice", "column",
                                          *fc.FIG_METRICS])
        w.writeheader()
        w.writerows(table)

    tex = os.path.join(out, f"{fc.NAME}.tex")
    write_tex(tex, headers, panels, labels)
    print(f"wrote {tex}")
    if a.no_compile:
        return
    latex = find_tool("pdflatex")
    if latex is None:
        print("[make_figure] no pdflatex found -- compile the .tex elsewhere "
              "(Overleaf: upload the folder), or install MiKTeX / TeX Live")
        return
    r = subprocess.run([latex, "-interaction=nonstopmode", "-halt-on-error",
                        os.path.basename(tex)], cwd=out, capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stdout[-3000:])
        raise SystemExit("pdflatex failed (log above)")
    for ext in (".aux", ".log"):
        p = os.path.join(out, fc.NAME + ext)
        if os.path.exists(p):
            os.remove(p)
    pdf = os.path.join(out, f"{fc.NAME}.pdf")
    print(f"wrote {pdf}")
    ppm = find_tool("pdftoppm")
    if ppm:
        subprocess.run([ppm, "-png", "-r", "300", "-singlefile", pdf,
                        os.path.join(out, fc.NAME)], capture_output=True)
        print(f"wrote {os.path.join(out, fc.NAME + '.png')}")


if __name__ == "__main__":
    main()
